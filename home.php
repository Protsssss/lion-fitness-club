            async function purchase(event) {
                event.preventDefault();
                var abonementType   = document.getElementById("abonement-type-input").value;
                var name            = document.getElementById("name").value;
                var email           = document.getElementById("email").value;
                var phone           = document.getElementById("phone").value;
                var trainerType     = document.getElementById("trainer-type") ? document.getElementById("trainer-type").value : '';
                var additionalInfo  = document.getElementById("additional-info").value;

                try {
                    const res = await fetch('/cyber-platform/api/subscription', {
                        method: 'POST',
                        headers: { 'Content-Type': 'application/json' },
                        body: JSON.stringify({
                            abonement_type:  abonementType,
                            name:            name,
                            email:           email,
                            phone:           phone,
                            trainer_type:    trainerType,
                            additional_info: additionalInfo
                        })
                    });
                    const result = await res.json();
                    if (result.success) {
                        alert('✅ ' + result.message);
                        document.getElementById("purchase-success-message").style.display = "block";
                        closeModal();
                    } else {
                        alert('❌ ' + result.message);
                    }
                } catch(e) {
                    alert('Помилка зєднання з сервером');
                }
            }
